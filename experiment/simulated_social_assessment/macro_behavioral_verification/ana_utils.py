def verify_power_law_fit(data_values: List[float], output_file_path) -> Tuple[float, float]:
    """
    Power law distribution fitting
    Calculate the power law goodness of fit (R^2) and power exponent (Alpha) for a set of data.
    Used to verify whether content popularity and follower counts follow a "long-tail distribution."

    Args:
        data_values (List[float] or List[int]):
            List of numerical values to be analyzed.
            - Type: List of floats or integers
            - Format: [Value 1, Value 2, Value 3, ...]
            - Constraints: List length should be greater than 10 to ensure statistical significance; no pre-sorting required; zero values will be automatically filtered.

    Example:
        # Assume this is the list of like counts extracted from all content
        input_data = [1024, 512, 128, 64, 32, 1, 0, 1, 5]
        r2, alpha = verify_power_law_fit(input_data)

    Returns:
        Tuple[float, float]: (R_squared, Alpha)
            - R_squared: Goodness of fit (0~1), the closer to 1, the more it conforms to the power law.
            - Alpha: Power law index, social networks are usually between 2.0 and 3.0.
    """
    # 1. Data cleaning: Filter 0 and negative numbers (log cannot handle), and sort from largest to smallest
    clean_data = [float(x) for x in data_values if x > 0]
    if len(clean_data) < 2:
        print("Error: Insufficient valid data (N < 2), unable to fit.")
        return 0.0, 0.0

    clean_data.sort(reverse=True)

    # 2. Convert to log-log coordinates (Log-Log Plot)
    # X-axis: Rank (1, 2, 3...)
    # Y-axis: Value (1024, 512...)
    ranks = np.arange(1, len(clean_data) + 1)
    log_ranks = np.log10(ranks)
    log_values = np.log10(clean_data)

    # 3. Linear regression fitting
    slope, intercept, r_value, p_value, std_err = linregress(log_ranks, log_values)

    r_squared = r_value ** 2
    alpha = -slope  # Slope is usually negative, Alpha takes positive value

    # 4. Plotting (optional, for debugging)
    plt.figure(figsize=(6, 4))
    plt.scatter(log_ranks, log_values, alpha=0.5, s=10, label='Raw Data')
    plt.plot(log_ranks, slope * log_ranks + intercept, 'r--', label=f'Fit (R2={r_squared:.2f})')
    plt.xlabel('Log(Rank)')
    plt.ylabel('Log(Value)')
    plt.title(f'Power Law Verification (alpha={alpha:.2f})')
    plt.legend()

    if not os.path.exists(output_file_path):
        os.makedirs(output_file_path, exist_ok=True)
    plt.savefig(fr'{output_file_path}\Power_Law_Distribution_Fit.png', dpi=300, bbox_inches='tight')
    # 4. Close canvas (release memory, preventing the program from "running slower and slower")
    plt.close()

    return round(r_squared, 2), round(alpha, 2)


def compare_time_series_trends(timeline_a: List[float], timeline_b: List[float], metric_name: str, output_file_path) -> float:
    """
    KPI time series trend comparison
    Compare the trend of a certain KPI over time under two sets of strategies, and calculate the average gap.
    Used to verify whether the logic of extreme tests such as "strict regulation vs laissez-faire" meets expectations.

    Args:
        timeline_a (List[float]):
            List of KPI values generated by Strategy A (e.g., laissez-faire strategy) each day.
            - Format: [Day 1 value, Day 2 value, ..., Day N value]
        timeline_b (List[float]):
            List of KPI values generated by Strategy B (e.g., strict regulation strategy) each day.
            - Format: [Day 1 value, Day 2 value, ..., Day N value]
            - Note: It is best for timeline_a and timeline_b to have consistent lengths.
        metric_name (str):
            Name of the KPI, used only for chart title display (e.g., "Creativity", "Safety").

    Example:
        # Simulate 5 days of creativity index
        creativity_free = [0.8, 0.85, 0.90, 0.88, 0.92]
        creativity_strict = [0.8, 0.60, 0.40, 0.20, 0.10]
        diff = compare_time_series_trends(creativity_free, creativity_strict, "Creativity")

    Returns:
        float: Average difference value (Mean Difference).
               If it is "A - B", positive values indicate higher performance in Group A.
    """
    # Ensure length alignment
    min_len = min(len(timeline_a), len(timeline_b))
    data_a = timeline_a[:min_len]
    data_b = timeline_b[:min_len]
    days = range(1, min_len + 1)

    # 1. Plotting comparison
    plt.figure(figsize=(8, 4))
    plt.plot(days, data_a, label='Group A', marker='o', linestyle='--')
    plt.plot(days, data_b, label='Group B', marker='x', linestyle='-')
    plt.xlabel('Simulation Day')
    plt.ylabel(metric_name)
    plt.title(f'Mechanism Verification: {metric_name} Trends')
    plt.legend()
    plt.grid(True, alpha=0.3)

    if not os.path.exists(output_file_path):
        os.makedirs(output_file_path, exist_ok=True)
    plt.savefig(fr'{output_file_path}\{metric_name}.png', dpi=300, bbox_inches='tight')
    # 4. Close canvas (release memory, preventing the program from "running slower and slower")
    plt.close()

    # 2. Calculate average gap
    diffs = [a - b for a, b in zip(data_a, data_b)]
    avg_diff = sum(diffs) / len(diffs)

    return round(avg_diff, 2)


def calculate_clustering_coefficient(edges: List[Tuple[str, str]]) -> float:
    """
    Network authenticity: Clustering coefficient
    Build a network graph based on a list of social relationships and calculate the average clustering coefficient.
    Used to verify whether the social network has "clique" characteristics (Clustering).

    Args:
        edges (List[Tuple[str, str]]):
            List of edges in the social network.
            - Type: List containing tuples, each tuple representing a follow relationship.
            - Format: [(Follower ID, Followed ID), (A, B), (B, C), ...]
            - Note: IDs must be strings or integers.

    Example:
        # User relationship data
        social_graph_edges = [
            ("user_1", "user_2"),
            ("user_2", "user_3"),
            ("user_3", "user_1"),  # Forming a closed-loop triangle
            ("user_4", "user_5")
        ]
        coef = calculate_clustering_coefficient(social_graph_edges)

    Returns:
        float: Average clustering coefficient (0.0 ~ 1.0).
               Real social networks are usually > 0.1, random networks are usually close to 0.
    """
    if not edges:
        print("Error: Edge list is empty, unable to build network.")
        return 0.0

    # 1. Build a directed graph
    G = nx.DiGraph()
    G.add_edges_from(edges)

    # 2. Calculate average clustering coefficient
    # NetworkX's average_clustering will automatically handle directed graphs
    # (Some versions might treat it as an undirected graph calculation, which is usually an acceptable approximation in social simulation benchmarks)
    try:
        avg_clustering = nx.average_clustering(G)
    except Exception as e:
        print(f"Calculation Error: {e}")
        return 0.0

    return round(avg_clustering, 2)  # Keep two decimal places


def calculate_homophily_score(edges: List[Tuple[str, str]], node_attributes: Dict[str, str]) -> float:
    """
    Social dynamics: Homophily coefficient
    Calculate the network's attribute assortativity coefficient (Assortativity).
    Verify the "birds of a feather flock together" phenomenon: do users of the same type tend to follow each other?

    Args:
        edges (List[Tuple[str, str]]):
            List of edges in the social network (same as above).
            - Format: [("user_A", "user_B"), ("user_C", "user_A")]

        node_attributes (Dict[str, str]):
            Node attribute dictionary. Key is user ID, value is user type/attribute.
            - Format: {"user_A": "Rebel", "user_B": "Rebel", "user_C": "Trust"}
            - Constraints: Keys in the dictionary must cover the node IDs appearing in edges.

    Example:
        edges = [("u1", "u2"), ("u3", "u4")]
        # u1 follows u2 (both Rebel), u3 follows u4 (both Trust) -> high homophily
        attrs = {"u1": "Rebel", "u2": "Rebel", "u3": "Trust", "u4": "Trust"}
        score = calculate_homophily_score(edges, attrs)

    Returns:
        float: Assortativity coefficient (-1.0 ~ 1.0).
            - Positive value (>0): Homophily.
            - 0: Random connection.
            - Negative value (<0): Heterophily.
    """
    if not edges or not node_attributes:
        return 0.0

    # 1. Build graph
    G = nx.DiGraph()
    G.add_edges_from(edges)

    # 2. Bind attributes to nodes
    # This step is crucial: attributes in the dictionary must be assigned to nodes in the graph
    # We only assign values to nodes that actually exist in the graph to avoid errors
    valid_attrs = {n: node_attributes[n] for n in G.nodes() if n in node_attributes}
    nx.set_node_attributes(G, valid_attrs, 'user_type')

    # 3. Calculate assortativity coefficient for discrete attributes
    try:
        # 'user_type' is the attribute key name we set in the previous step
        score = nx.attribute_assortativity_coefficient(G, 'user_type')

        # Handle possible NaN (when the network is completely disconnected or attributes are completely identical causing the denominator to be 0)
        if np.isnan(score):
            return 0.0

    except Exception as e:
        print(f"Error computing assortativity: {e}")
        return 0.0

    return round(score, 2)


def calculate_gini_coefficient(wealth_distribution: List[float]) -> float:
    """
    Ecological evolution: Gini coefficient
    Calculate the Gini coefficient to measure the degree of inequality in resource distribution.
    Used to verify whether influence exhibits the Matthew Effect (the rich get richer).

    Args:
        wealth_distribution (List[float]):
            List of resource values for each individual (e.g., influence, total likes, points).
            - Format: [User A influence, User B influence, User C influence, ...]
            - Constraints: Values cannot be negative.

    Example:
        # Extreme inequality: one person owns all resources
        influences = [0, 0, 0, 0, 100]
        gini = calculate_gini_coefficient(influences) # Close to 1.0

    Returns:
        float: Gini coefficient (0.0 ~ 1.0).
            - 0.0: Perfect equality.
            - 1.0: Absolute inequality.
            - Above 0.4: Usually considered the inequality warning line.
    """
    # 1. Data preprocessing
    wealths = [x for x in wealth_distribution if x >= 0]
    if not wealths or sum(wealths) == 0:
        return 0.0

    # 2. Sorting (Gini coefficient calculation must be sorted)
    wealths = sorted(wealths)
    n = len(wealths)

    # 3. Calculate using the Lorenz curve area formula
    # Formula: G = (2 * sum(i * x_i)) / (n * sum(x_i)) - (n + 1) / n
    # Where i is 1-based index (1, 2, ..., n)

    index = np.arange(1, n + 1)
    numerator = np.sum(index * wealths)
    denominator = n * np.sum(wealths)

    gini = (2 * numerator) / denominator - (n + 1) / n

    return round(float(gini), 2)